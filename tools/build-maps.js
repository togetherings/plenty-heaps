#!/usr/bin/env node
/**
 * build-maps.js
 * =============
 * Converts every Tiled map in  maps-src/*.tmj  into a small script file in
 * src/data/maps/<name>.js  that registers the map data on  FarmSim.Maps.
 *
 * WHY: Loading .json files at runtime needs a network request (XHR/fetch).
 * Wrapping the map in a <script> means it loads like any other code file, which
 * works the same in Kolibri, in a SCORM LMS, and when testing locally.
 *
 * WORKFLOW:
 *   1. Edit or create maps in Tiled (https://www.mapeditor.org), saving as .tmj
 *      in maps-src/. Use the "tiles" tileset (assets/tiles.png).
 *   2. Run:  node tools/build-maps.js
 *   3. For a NEW map, also add a <script> tag in index.html and an entry in
 *      src/data/areas.js (see README "Adding a new area").
 *
 * The script also does a few sanity checks so mistakes show up here rather
 * than as a blank screen in the game.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'maps-src');
const OUT_DIR = path.join(ROOT, 'src', 'data', 'maps');

// Layers every map must have, in the names the game code expects.
const REQUIRED_TILE_LAYERS = ['ground', 'decor'];
const REQUIRED_OBJECT_LAYER = 'objects';

function check(map, name) {
  const problems = [];
  if (map.infinite) problems.push('map must not be "infinite" (Map > Map Properties)');
  if (map.tilewidth !== 16 || map.tileheight !== 16) problems.push('tiles must be 16x16');
  const layerNames = map.layers.map(l => l.name);
  REQUIRED_TILE_LAYERS.forEach(n => {
    if (layerNames.indexOf(n) === -1) problems.push('missing tile layer "' + n + '"');
  });
  if (layerNames.indexOf(REQUIRED_OBJECT_LAYER) === -1) problems.push('missing object layer "objects"');
  map.layers.forEach(l => {
    if (l.type === 'tilelayer' && typeof l.data === 'string') {
      problems.push('layer "' + l.name + '" is compressed; set Tile Layer Format to CSV in Map Properties');
    }
  });
  const ts = map.tilesets || [];
  if (!ts.length || ts[0].name !== 'tiles') problems.push('first tileset must be named "tiles" and be embedded');
  if (ts.length && ts[0].source) problems.push('tileset is external (.tsx); embed it (Map > Embed Tilesets)');
  if (problems.length) {
    throw new Error('Map "' + name + '":\n  - ' + problems.join('\n  - '));
  }
}

function main() {
  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
  const files = fs.readdirSync(SRC_DIR).filter(f => /\.tmj$/.test(f));  // maps only (tileset.json is not a map)
  files.forEach(file => {
    const name = file.replace(/\.(tmj|json)$/, '');
    const map = JSON.parse(fs.readFileSync(path.join(SRC_DIR, file), 'utf8'));
    check(map, name);
    const out =
      '// AUTO-GENERATED by tools/build-maps.js from maps-src/' + file + '\n' +
      '// Do not edit by hand: edit the .tmj file in Tiled, then re-run the tool.\n' +
      'FarmSim.Maps = FarmSim.Maps || {};\n' +
      'FarmSim.Maps[' + JSON.stringify(name) + '] = ' + JSON.stringify(map) + ';\n';
    fs.writeFileSync(path.join(OUT_DIR, name + '.js'), out);
    console.log('built src/data/maps/' + name + '.js');
  });
}

main();
